export function getBonusYaoCommentary(num: number | null): string | undefined {
  if (num === null) {
    return undefined;
  }

  const commentary = BONUS_YAO_COMMENTARY_BY_NUM[num];
  return commentary && commentary.trim().length > 0 ? commentary : undefined;
}
